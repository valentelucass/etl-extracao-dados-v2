CREATE OR ALTER VIEW pub.raster_viagens
AS
SELECT r.source_key AS cod_solicitacao,j.sequencial,j.cod_filial,
       CONVERT(nvarchar(10),TRIM(j.status_viagem)) AS status_viagem,
       CONVERT(nvarchar(20),TRIM(j.placa_veiculo)) AS placa_veiculo,
       CONVERT(nvarchar(20),TRIM(j.placa_carreta1)) AS placa_carreta1,
       CONVERT(nvarchar(20),TRIM(COALESCE(j.placa_carreta02,j.placa_carreta2))) AS placa_carreta2,
       CONVERT(nvarchar(20),TRIM(j.placa_carreta3)) AS placa_carreta3,
       CONVERT(nvarchar(20),TRIM(j.cpf_motorista1)) AS cpf_motorista1,
       CONVERT(nvarchar(20),TRIM(j.cpf_motorista2)) AS cpf_motorista2,
       CONVERT(nvarchar(20),TRIM(j.cnpj_cliente_orig)) AS cnpj_cliente_orig,
       CONVERT(nvarchar(20),TRIM(j.cnpj_cliente_dest)) AS cnpj_cliente_dest,
       j.cod_ibge_cidade_orig,j.cod_ibge_cidade_dest,
       core.dashboard_raster_time(j.data_hora_prev_ini) AS data_hora_prev_ini,
       core.dashboard_raster_time(j.data_hora_prev_fim) AS data_hora_prev_fim,
       core.dashboard_raster_time(j.data_hora_real_ini) AS data_hora_real_ini,
       core.dashboard_raster_time(j.data_hora_real_fim) AS data_hora_real_fim,
       core.dashboard_raster_time(j.data_hora_identificou_fim_viagem) AS data_hora_identificou_fim_viagem,
       CASE WHEN j.tempo_total_viagem_min BETWEEN 0 AND 43200 THEN j.tempo_total_viagem_min END AS tempo_total_viagem_min,
       CONVERT(nvarchar(5),TRIM(j.dentro_prazo_raster)) AS dentro_prazo_raster,
       j.percentual_atraso_raster,
       CONVERT(nvarchar(5),TRIM(j.rodou_fora_horario)) AS rodou_fora_horario,
       j.velocidade_media,j.eventos_velocidade,j.desvios_de_rota,j.cod_rota,
       CONVERT(nvarchar(500),TRIM(j.rota_descricao)) AS rota_descricao,
       CONVERT(nvarchar(1000),TRIM(COALESCE(j.link_timeline,j.link_timeline_variant))) AS link_timeline,
       r.record_json AS metadata,
       r.observed_utc AS data_extracao,CONVERT(bit,0) AS excluido_na_origem,
       CONVERT(datetime2(0),NULL) AS data_exclusao_origem
FROM core.dashboard_raster_vigente r
CROSS APPLY OPENJSON(r.record_json) WITH(
    sequencial bigint '$.Sequencial',
    cod_filial int '$.CodFilial',
    status_viagem nvarchar(max) '$.StatusViagem',
    placa_veiculo nvarchar(max) '$.PlacaVeiculo',
    placa_carreta1 nvarchar(max) '$.PlacaCarreta1',
    placa_carreta02 nvarchar(max) '$.PlacaCarreta02',
    placa_carreta2 nvarchar(max) '$.PlacaCarreta2',
    placa_carreta3 nvarchar(max) '$.PlacaCarreta3',
    cpf_motorista1 nvarchar(max) '$.CPFMotorista1',
    cpf_motorista2 nvarchar(max) '$.CPFMotorista2',
    cnpj_cliente_orig nvarchar(max) '$.CNPJClienteOrig',
    cnpj_cliente_dest nvarchar(max) '$.CNPJClienteDest',
    cod_ibge_cidade_orig bigint '$.CodIBGECidadeOrig',
    cod_ibge_cidade_dest bigint '$.CodIBGECidadeDest',
    data_hora_prev_ini nvarchar(100) '$.DataHoraPrevIni',
    data_hora_prev_fim nvarchar(100) '$.DataHoraPrevFim',
    data_hora_real_ini nvarchar(100) '$.DataHoraRealIni',
    data_hora_real_fim nvarchar(100) '$.DataHoraRealFim',
    data_hora_identificou_fim_viagem nvarchar(100) '$.DataHoraIdentificouFimViagem',
    tempo_total_viagem_min int '$.TempoTotalViagem',
    dentro_prazo_raster nvarchar(max) '$.DentroPrazo',
    percentual_atraso_raster decimal(10,2) '$.PercentualAtraso',
    rodou_fora_horario nvarchar(max) '$.RodouForaHorario',
    velocidade_media decimal(10,2) '$.VelocidadeMedia',
    eventos_velocidade int '$.EventosVelocidade',
    desvios_de_rota int '$.DesviosDeRota',
    cod_rota bigint '$.Rota.CodRota',
    rota_descricao nvarchar(max) '$.Rota.Descricao',
    link_timeline nvarchar(max) '$.LinkTimeLine',
    link_timeline_variant nvarchar(max) '$.LinkTimeline'
) j;
