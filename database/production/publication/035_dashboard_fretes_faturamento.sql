CREATE OR ALTER VIEW pub.fato_fretes_faturamento
AS
SELECT
    id AS [frete_id],
    corporation_sequence_number AS [numero_minuta],
    TODATETIMEOFFSET(CONVERT(datetime2(7),cal.data_referencia_faturamento),DATEPART(TZOFFSET,f.billing_date)) AS [data_referencia_faturamento],
    cal.data_referencia_faturamento AS [data_referencia_faturamento_date],
    YEAR(cal.data_referencia_faturamento)*100+MONTH(cal.data_referencia_faturamento) AS [data_referencia_faturamento_yyyymm],
    billing_date AS [data_referencia_faturamento_real],
    CONVERT(date,billing_date) AS [data_referencia_faturamento_real_date],
    YEAR(billing_date)*100+MONTH(billing_date) AS [data_referencia_faturamento_real_yyyymm],
    CONVERT(bit,CASE WHEN cal.data_referencia_faturamento<>CONVERT(date,billing_date) THEN 1 ELSE 0 END) AS [is_data_faturamento_retroagida],
    service_at AS [data_frete],
    CONVERT(date,service_at) AS [data_frete_date],
    cte_issued_at AS [data_emissao_cte],
    created_at AS [criado_em],
    resolved_branch_id AS [filial_id],
    billing_branch AS [filial_nome],
    billing_branch_key AS [filial_key],
    NULLIF(TRIM(branch_name),N'') AS [filial_apelido],
    branch_document AS [filial_cnpj],
    destination_branch AS [responsavel_regiao_destino],
    CONVERT(nvarchar(255),COALESCE(LOWER(destination_branch),N'sem_responsavel')) AS [responsavel_regiao_destino_key],
    destination_region AS [regiao_destino],
    payer_id AS [pagador_id],
    NULLIF(TRIM(payer_name),N'') AS [pagador_nome],
    NULLIF(TRIM(payer_document),N'') AS [pagador_documento],
    CONVERT(nvarchar(50),payer_key) AS [pagador_documento_key],
    sender_id AS [remetente_id],
    NULLIF(TRIM(sender_name),N'') AS [remetente_nome],
    NULLIF(TRIM(sender_document),N'') AS [remetente_documento],
    receiver_id AS [destinatario_id],
    NULLIF(TRIM(receiver_name),N'') AS [destinatario_nome],
    NULLIF(TRIM(receiver_document),N'') AS [destinatario_documento],
    NULLIF(TRIM(origin_city),N'') AS [origem_cidade],
    NULLIF(TRIM(origin_state),N'') AS [origem_uf],
    NULLIF(TRIM(destination_city),N'') AS [destino_cidade],
    NULLIF(TRIM(destination_state),N'') AS [destino_uf],
    NULLIF(TRIM(status),N'') AS [status_frete],
    CONVERT(nvarchar(50),LOWER(NULLIF(TRIM(CASE status WHEN N'pending' THEN N'pendente' WHEN N'finished' THEN N'finalizado' WHEN N'in_transit' THEN N'em transito' WHEN N'standby' THEN N'aguardando' WHEN N'manifested' THEN N'registrado' WHEN N'occurrence_treatment' THEN N'tratamento de ocorrencia' ELSE status END),N''))) AS [status_frete_norm],
    NULLIF(TRIM(classification),N'') AS [classificacao_nome],
    CONVERT(nvarchar(255),NULL) AS [centro_custo_nome],
    CONVERT(nvarchar(100),NULLIF(TRIM(REPLACE(type,N'Freight::',N'')),N'')) AS [tipo_frete],
    NULLIF(TRIM(modal),N'') AS [modal],
    NULLIF(TRIM(modal),N'') AS [modal_cte],
    NULLIF(TRIM(price_table),N'') AS [tabela_preco_nome],
    NULLIF(TRIM(user_name),N'') AS [usuario_nome],
    NULLIF(TRIM(reference_number),N'') AS [reference_number],
    cte_id AS [cte_id],
    NULLIF(TRIM(cte_key),N'') AS [chave_cte],
    TRY_CONVERT(int,cte_number) AS [numero_cte],
    TRY_CONVERT(int,cte_series) AS [serie_cte],
    NULLIF(TRIM(cte_emission_type),N'') AS [cte_emission_type],
    cte_created_at AS [cte_created_at],
    cte_real_status AS [status_cte_real],
    cte_result AS [status_cte_result],
    LOWER(cte_real_status) AS [status_cte_norm],
    CONVERT(nvarchar(255),cancellation_evidence) AS [cte_cancelado_evidencia],
    has_cte AS [is_documento_cte],
    CONVERT(bit,CASE WHEN cancellation_evidence IS NULL THEN 0 ELSE 1 END) AS [is_cte_cancelado],
    TRY_CONVERT(int,nfse_number) AS [nfse_number],
    NULLIF(TRIM(nfse_series),N'') AS [nfse_series],
    NULLIF(TRIM(nfse_status),N'') AS [nfse_status],
    CONVERT(date,nfse_issued_at) AS [nfse_issued_at],
    CONVERT(bit,COALESCE(courtesy,0)) AS [is_cortesia],
    blocked AS [is_bloqueio_faturamento],
    origin_eligible AS [is_elegivel_origem],
    billing_eligible AS [is_elegivel_faturamento],
    subtotal AS [valor_frete_original],
    COALESCE(total,CONVERT(decimal(18,2),0)) AS [receita_bruta_original],
    CASE WHEN billing_eligible=1 THEN subtotal ELSE CONVERT(decimal(18,2),0) END AS [valor_frete],
    CASE WHEN billing_eligible=1 THEN COALESCE(total,CONVERT(decimal(18,2),0)) ELSE CONVERT(decimal(18,2),0) END AS [receita_bruta],
    invoices_value AS [valor_notas],
    invoices_weight AS [peso_notas],
    taxed_weight AS [peso_taxado],
    real_weight AS [peso_real],
    cubages_cubed_weight AS [peso_cubado],
    total_cubic_volume AS [total_m3],
    volumes AS [volumes],
    CONVERT(bit,0) AS [excluido_na_origem],
    CONVERT(datetime2(0),NULL) AS [data_exclusao_origem],
    CONVERT(datetime2(0),freshness.snapshot_at) AS [ultima_reconciliacao_origem_em],
    CONVERT(datetime2(0),freshness.origin_at) AS [data_extracao_origem],
    CONVERT(datetime2(0),cte_stored_utc) AS [data_extracao_faturas],
    CONVERT(datetime2(0),freshness.snapshot_at) AS [snapshot_em],
    CONVERT(binary(32),HASHBYTES('SHA2_256',CONCAT_WS(N'|',metadata,created_at,invoices_weight,finished_at,cte_real_status,cte_result,billing_branch_key,destination_branch,destination_region,volumes,cal.data_referencia_faturamento))) AS [hash_linha]
FROM core.dashboard_fretes_publicacao f
JOIN pub.dim_calendario cal ON cal.data=CONVERT(date,f.billing_date)
CROSS APPLY (
    SELECT GREATEST(f.stored_utc,f.location_stored_utc) AS origin_at,
           GREATEST(f.stored_utc,f.location_stored_utc,f.cte_stored_utc) AS snapshot_at
) freshness;
