CREATE OR ALTER VIEW pub.vw_fretes_powerbi
AS
SELECT
    CONVERT(time(0),service_at) AS [Hora (Solicitacao)],
    id AS [ID],
    corporation_sequence_number AS [Nº Minuta],
    cte_key AS [Chave CT-e],
    TRY_CONVERT(int,cte_number) AS [Nº CT-e],
    TRY_CONVERT(int,cte_series) AS [Série],
    cte_issued_at AS [CT-e Emissão],
    billing_date AS [data_referencia_faturamento],
    cte_emission_type AS [CT-e Tipo Emissão],
    cte_id AS [CT-e ID],
    cte_created_at AS [CT-e Criado em],
    CONVERT(varchar(20),CASE WHEN has_cte=1 THEN N'CT-e' WHEN nfse_number IS NOT NULL OR NULLIF(TRIM(nfse_series),N'') IS NOT NULL THEN N'NFS-e' ELSE N'Pendente/Não Emitido' END) AS [Documento Oficial/Tipo],
    CASE WHEN has_cte=1 THEN cte_key END AS [Documento Oficial/Chave],
    CONVERT(nvarchar(50),CASE WHEN has_cte=1 THEN cte_number ELSE nfse_number END) AS [Documento Oficial/Número],
    CASE WHEN has_cte=1 THEN CONVERT(nvarchar(50),cte_series) ELSE nfse_series END AS [Documento Oficial/Série],
    CONVERT(nvarchar(max),NULL) AS [Documento Oficial/XML],
    service_at AS [Data frete],
    created_at AS [Criado em],
    total AS [Valor Total do Serviço],
    invoices_value AS [Valor NF],
    invoices_weight AS [Kg NF],
    subtotal AS [Valor Frete],
    volumes AS [Volumes],
    taxed_weight AS [Kg Taxado],
    taxed_weight AS [Peso Taxado],
    real_weight AS [Kg Real],
    real_weight AS [Peso Real],
    cubages_cubed_weight AS [Kg Cubado],
    cubages_cubed_weight AS [Peso Cubado],
    total_cubic_volume AS [M3],
    total_cubic_volume AS [Total M3],
    payer_name AS [Pagador],
    payer_document AS [Pagador Doc],
    payer_id AS [Pagador ID],
    sender_name AS [Remetente],
    sender_document AS [Remetente Doc],
    sender_id AS [Remetente ID],
    origin_city AS [Origem],
    origin_state AS [UF Origem],
    receiver_name AS [Destinatario],
    receiver_document AS [Destinatario Doc],
    receiver_id AS [Destinatario ID],
    destination_city AS [Destino],
    destination_city AS [Cidade Destino],
    destination_state AS [UF Destino],
    destination_region AS [Região Destino],
    branch_name AS [Filial],
    branch_name AS [Filial Emissora],
    COALESCE(destination_branch,branch_name) AS [Responsável pela Região de Destino],
    CONVERT(nvarchar(255),COALESCE(LOWER(destination_branch),LOWER(NULLIF(TRIM(branch_name),N'')),N'sem_responsavel')) AS [Responsável Região Destino Key],
    branch_name AS [Filial Apelido],
    branch_document AS [Filial CNPJ],
    price_table AS [Tabela de Preço],
    classification AS [Classificação],
    CONVERT(nvarchar(255),NULL) AS [Centro de Custo],
    user_name AS [Usuário],
    notes.invoice_numbers AS [NF],
    reference_number AS [Referência],
    resolved_branch_id AS [Corp ID],
    city.cidade_id AS [Cidade Destino ID],
    delivery_forecast AS [Previsão de Entrega],
    finished_at AS [Data de Finalização],
    performance_completion AS [Finalização da Performance],
    performance_days AS [Performance Diferença de Dias],
    CONVERT(varchar(13),CASE WHEN performance_days<=0 THEN 'NO PRAZO' WHEN performance_days>0 THEN 'FORA DO PRAZO' END) AS [Performance Status],
    performance.delay_label AS [Performance Status Dif de Dias],
    performance.delay_label AS [Performance Status Dif de Dias Oficial],
    CONVERT(nvarchar(3),CASE WHEN EXISTS (SELECT 1 FROM pub.vw_inventario_powerbi p WHERE p.[Nº Minuta]=f.corporation_sequence_number AND p.[Comprovante Anexado]=N'Sim') THEN N'Sim' ELSE N'Não' END) AS [Comprovante Anexado],
    modal AS [Modal],
    CONVERT(nvarchar(50),CASE status WHEN N'pending' THEN N'pendente' WHEN N'finished' THEN N'finalizado' WHEN N'done' THEN N'finalizado' WHEN N'canceled' THEN N'cancelada' WHEN N'cancelled' THEN N'cancelada' WHEN N'in_transit' THEN N'em trânsito' WHEN N'standby' THEN N'aguardando' WHEN N'manifested' THEN N'registrado' WHEN N'occurrence_treatment' THEN N'tratamento de ocorrência' ELSE status END) AS [Status],
    CONVERT(varchar(3),CASE courtesy WHEN 1 THEN N'Sim' WHEN 0 THEN N'Não' END) AS [Cortesia],
    courtesy AS [Cortesia Flag],
    origin_eligible AS [is_elegivel_faturamento],
    CONVERT(nvarchar(4000),REPLACE(type,N'Freight::',N'')) AS [Tipo Frete],
    TRY_CONVERT(int,service_type) AS [Service Type],
    CONVERT(varchar(10),CASE insurance_enabled WHEN 1 THEN 'Com seguro' WHEN 0 THEN 'Sem seguro' END) AS [Seguro Habilitado],
    gris_subtotal AS [GRIS],
    tde_subtotal AS [TDE],
    freight_weight_subtotal AS [Frete Peso],
    ad_valorem_subtotal AS [Ad Valorem],
    toll_subtotal AS [Pedágio],
    itr_subtotal AS [ITR],
    modal AS [Modal CT-e],
    redispatch_subtotal AS [Redispatch],
    suframa_subtotal AS [SUFRAMA],
    CASE payment_type WHEN N'bill' THEN N'cobrança' WHEN N'cash' THEN N'dinheiro' ELSE payment_type END AS [Tipo Pagamento],
    CONVERT(nvarchar(50),NULL) AS [Doc Anterior],
    CONVERT(decimal(18,2),NULL) AS [Valor Produtos],
    trt_subtotal AS [TRT],
    fiscal_cst AS [ICMS CST],
    fiscal_cfop AS [CFOP],
    fiscal_icms AS [Valor ICMS],
    fiscal_pis AS [Valor PIS],
    fiscal_cofins AS [Valor COFINS],
    fiscal_base AS [Base de Cálculo ICMS],
    fiscal_icms_rate AS [Alíquota ICMS %],
    fiscal_pis_rate AS [Alíquota PIS %],
    fiscal_cofins_rate AS [Alíquota COFINS %],
    CONVERT(varchar(10),CASE fiscal_has_difal WHEN 1 THEN N'possui' WHEN 0 THEN N'não possui' END) AS [Possui DIFAL],
    fiscal_difal_origin AS [DIFAL Origem],
    fiscal_difal_destination AS [DIFAL Destino],
    nfse_series AS [Série NFS-e],
    TRY_CONVERT(int,nfse_number) AS [Nº NFS-e],
    CONVERT(nvarchar(50),NULL) AS [NFS-e/ID Integração],
    nfse_status AS [NFS-e/Status],
    CONVERT(date,nfse_issued_at) AS [NFS-e/Emissão],
    nfse_cancellation_reason AS [NFS-e/Cancelamento/Motivo],
    CONVERT(nvarchar(1000),NULL) AS [NFS-e/PDF],
    CONVERT(bigint,NULL) AS [NFS-e/Filial ID],
    CONVERT(nvarchar(500),NULL) AS [NFS-e/Serviço/Descrição],
    CONVERT(nvarchar(max),NULL) AS [NFS-e/XML],
    CONVERT(bigint,NULL) AS [Seguro ID],
    other_fees AS [Outras Tarifas],
    km AS [KM],
    TRY_CONVERT(int,payment_accountable_type) AS [Tipo Contábil Pagamento],
    CONVERT(decimal(18,2),NULL) AS [Valor Segurado],
    CONVERT(varchar(10),NULL) AS [Globalizado],
    sec_cat_subtotal AS [SEC/CAT],
    CONVERT(nvarchar(50),NULL) AS [Tipo Globalizado],
    CONVERT(int,NULL) AS [Tipo Contábil Tabela],
    TRY_CONVERT(int,insurance_accountable_type) AS [Tipo Contábil Seguro],
    metadata AS [Metadata],
    CONVERT(datetime2(7),stored_utc) AS [Data de extracao]
FROM core.dashboard_fretes_publicacao f
LEFT JOIN ref.dashboard_frete_cidade_destino city
    ON city.cidade_key=LOWER(TRIM(f.destination_city)) COLLATE Latin1_General_CI_AS
   AND city.uf=UPPER(TRIM(f.destination_state)) COLLATE Latin1_General_CI_AS
OUTER APPLY (
    SELECT STRING_AGG(CONVERT(nvarchar(max),j.value),N', ')
        WITHIN GROUP(ORDER BY TRY_CONVERT(int,j.[key])) AS invoice_numbers
    FROM OPENJSON(f.invoices_mapping) j WHERE j.type IN (1,2)
) notes
CROSS APPLY (
    SELECT CONVERT(varchar(25),CASE f.performance_days
        WHEN 0 THEN 'NO PRAZO' WHEN 1 THEN '1 DIA DE ATRASO' WHEN 2 THEN '2 DIAS DE ATRASO'
        WHEN 3 THEN '3 DIAS DE ATRASO' WHEN -1 THEN '1 DIA ANTES' WHEN -2 THEN '2 DIAS ANTES'
        WHEN -3 THEN '3 DIAS ANTES' ELSE CASE WHEN f.performance_days>3 THEN 'ACIMA DE 3 DIAS DE ATRASO'
                WHEN f.performance_days<-3 THEN 'ACIMA DE 3 DIAS ANTES' END END) AS delay_label
) performance
WHERE UPPER(NULLIF(TRIM(REPLACE(type,N'Freight::',N'')),N''))<>N'COMPLEMENTAR';
