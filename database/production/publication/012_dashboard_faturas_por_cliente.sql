CREATE OR ALTER VIEW pub.vw_faturas_por_cliente_powerbi
AS
SELECT CONVERT(time(0),f.data_emissao_cte) AS [Hora (Solicitacao)],
       f.unique_id AS [ID Único],
       CONVERT(nvarchar(255),f.filial) AS [Filial],
       CONVERT(nvarchar(50),f.estado) AS [Estado],
       f.numero_cte AS [CT-e/Número],
       CONVERT(nvarchar(50),COALESCE(f.numero_cte,f.numero_nfse)) AS [Número do Documento],
       CONVERT(nvarchar(100),f.chave_cte) AS [CT-e/Chave],
       f.data_emissao_cte AS [CT-e/Data de emissão],
       f.valor_frete AS [Frete/Valor dos CT-es],
       f.third_party_ctes_value AS [Terceiros/Valor CT-es],
       CONVERT(nvarchar(255),f.status_cte) AS [CT-e/Status],
       f.status_cte_result AS [CT-e/Resultado],
       CONVERT(nvarchar(100),f.tipo_frete) AS [Tipo],
       CONVERT(nvarchar(100),f.classificacao) AS [Classificação],
       CONVERT(nvarchar(255),f.pagador_nome) AS [Pagador do frete/Nome],
       CONVERT(nvarchar(50),f.pagador_documento) AS [Pagador do frete/Documento],
       CONVERT(nvarchar(4000),f.cliente_cnpj) AS [Cliente/CNPJ],
       CONVERT(nvarchar(255),f.remetente_nome) AS [Remetente/Nome],
       CONVERT(nvarchar(50),f.remetente_documento) AS [Remetente/Documento],
       CONVERT(nvarchar(255),f.destinatario_nome) AS [Destinatário/Nome],
       CONVERT(nvarchar(50),f.destinatario_documento) AS [Destinatário/Documento],
       CONVERT(nvarchar(255),f.vendedor_nome) AS [Vendedor/Nome],
       f.numero_nfse AS [NFS-e/Número],
       f.serie_nfse AS [NFS-e/Série],
       f.numero_nfse AS [fit_nse_number],
       f.numero_nfse AS [N° NFS-e],
       CONVERT(nvarchar(50),NULL) AS [Carteira/Descrição],
       CONVERT(nvarchar(max),NULL) AS [Instrução Customizada],
       CASE WHEN f.fit_ant_document IS NOT NULL THEN 'Faturado' ELSE 'Aguardando Faturamento' END AS [Status do Processo],
       CONVERT(nvarchar(50),f.fit_ant_document) AS [Fatura/N° Documento],
       CONVERT(nvarchar(10),f.fit_ant_issue_date,23) AS [Fatura/Emissão],
       f.fit_ant_value AS [Fatura/Valor],
       f.valor_fatura AS [Fatura/Valor Total],
       CONVERT(nvarchar(50),f.numero_fatura) AS [Fatura/Número],
       CONVERT(nvarchar(10),f.data_emissao_fatura,23) AS [Fatura/Emissão Fatura],
       CONVERT(nvarchar(10),f.data_vencimento_fatura,23) AS [Parcelas/Vencimento],
       CONVERT(nvarchar(10),f.data_baixa_fatura,23) AS [Fatura/Baixa],
       CONVERT(nvarchar(10),f.fit_ant_ils_original_due_date,23) AS [Fatura/Data Vencimento Original],
       f.notas_fiscais AS [Notas Fiscais],
       f.pedidos_cliente AS [Pedidos/Cliente],
       f.metadata AS [Metadata],
       f.data_extracao AS [Data da Última Atualização]
FROM core.dashboard_faturas_vigentes f;
