-- Applies only to the newly created container; never touches another database or engine.
SET NOCOUNT ON;
SET XACT_ABORT ON;
SET LOCK_TIMEOUT 10000;
IF DB_NAME() <> N'master' OR @@TRANCOUNT <> 0
    THROW 55011, N'V2_DATABASE_CONFIG_REQUIRES_MASTER_AUTOCOMMIT', 1;
IF CONVERT(VARCHAR(32),SERVERPROPERTY('ProductVersion')) <> '16.0.1000.6'
   OR DB_ID(N'ETL_SISTEMA_V2') IS NULL
    THROW 55012, N'V2_DATABASE_CONFIG_PRECONDITION', 1;
IF EXISTS (SELECT 1 FROM sys.dm_exec_sessions
           WHERE database_id=DB_ID(N'ETL_SISTEMA_V2') AND session_id<>@@SPID)
    THROW 55013, N'V2_DATABASE_CONFIG_EXISTING_CONSUMER', 1;
ALTER DATABASE [ETL_SISTEMA_V2] SET COMPATIBILITY_LEVEL=160;
ALTER DATABASE [ETL_SISTEMA_V2] SET AUTO_CLOSE OFF;
ALTER DATABASE [ETL_SISTEMA_V2] SET AUTO_SHRINK OFF;
ALTER DATABASE [ETL_SISTEMA_V2] SET READ_COMMITTED_SNAPSHOT ON;
ALTER DATABASE [ETL_SISTEMA_V2] SET RECOVERY FULL;
ALTER DATABASE [ETL_SISTEMA_V2] SET TRUSTWORTHY OFF;
ALTER DATABASE [ETL_SISTEMA_V2] SET DB_CHAINING OFF;
ALTER DATABASE [ETL_SISTEMA_V2] SET PAGE_VERIFY CHECKSUM;
