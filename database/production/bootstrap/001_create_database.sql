-- New database container only. No schema install, application identity or route change.
SET NOCOUNT ON;
SET XACT_ABORT ON;
IF DB_NAME() <> N'master' OR @@TRANCOUNT <> 0
    THROW 55001, N'V2_DATABASE_CREATE_REQUIRES_MASTER_AUTOCOMMIT', 1;
IF CONVERT(VARCHAR(32), SERVERPROPERTY('ProductVersion')) <> '16.0.1000.6'
   OR CONVERT(NVARCHAR(128), SERVERPROPERTY('Edition')) NOT LIKE N'Standard Edition%'
    THROW 55002, N'V2_EXISTING_ENGINE_MISMATCH', 1;
IF DB_ID(N'ETL_SISTEMA_V2') IS NOT NULL
    THROW 55003, N'V2_DATABASE_ALREADY_EXISTS_RECONCILE_ONLY', 1;
IF NOT EXISTS (SELECT 1 FROM sys.fn_helpcollations() WHERE name=N'Latin1_General_100_CI_AS_SC')
    THROW 55004, N'V2_DATABASE_COLLATION_UNAVAILABLE', 1;
IF EXISTS (SELECT 1 FROM model.sys.database_principals
           WHERE is_fixed_role=0 AND name NOT IN(N'dbo',N'guest',N'INFORMATION_SCHEMA',N'sys',N'public'))
   OR EXISTS (SELECT 1 FROM model.sys.objects WHERE is_ms_shipped=0)
    THROW 55005, N'V2_MODEL_HAS_UNREVIEWED_APPLICATION_CONTENT', 1;
IF NOT EXISTS (SELECT 1 FROM sys.dm_os_volume_stats(DB_ID(N'master'),1)
               WHERE available_bytes >= CONVERT(BIGINT,2147483648))
    THROW 55006, N'V2_DATABASE_DISK_HEADROOM_REQUIRED', 1;

DECLARE @data NVARCHAR(4000)=CONVERT(NVARCHAR(4000),SERVERPROPERTY('InstanceDefaultDataPath'));
DECLARE @log NVARCHAR(4000)=CONVERT(NVARCHAR(4000),SERVERPROPERTY('InstanceDefaultLogPath'));
IF @data IS NULL OR @log IS NULL OR RIGHT(@data,1) NOT IN(N'\',N'/') OR RIGHT(@log,1) NOT IN(N'\',N'/')
    THROW 55007, N'V2_DATABASE_DEFAULT_PATH_REQUIRED', 1;
SET @data += N'ETL_SISTEMA_V2.mdf';
SET @log += N'ETL_SISTEMA_V2_log.ldf';
IF EXISTS (SELECT 1 FROM sys.master_files WHERE physical_name IN(@data,@log))
    THROW 55008, N'V2_DATABASE_FILE_ALREADY_REGISTERED', 1;
DECLARE @ddl NVARCHAR(MAX)=
 N'CREATE DATABASE [ETL_SISTEMA_V2] ON PRIMARY '
 +N'(NAME=N''ETL_SISTEMA_V2'',FILENAME=N'''+REPLACE(@data,N'''',N'''''')
 +N''',SIZE=128MB,FILEGROWTH=64MB) LOG ON '
 +N'(NAME=N''ETL_SISTEMA_V2_log'',FILENAME=N'''+REPLACE(@log,N'''',N'''''')
 +N''',SIZE=64MB,FILEGROWTH=64MB) COLLATE Latin1_General_100_CI_AS_SC;';
EXEC sys.sp_executesql @ddl;
